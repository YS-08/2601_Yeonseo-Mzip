  function demoSearch(q, reason, detail) {
    const lower = q.toLowerCase();
    const cats = [], tags = [];
    LEXICON.forEach(([words, out]) => {
      if (words.some(w => lower.indexOf(w) !== -1)) {
        (out.cats || []).forEach(c => { if (cats.indexOf(c) === -1) cats.push(c); });
        (out.tags || []).forEach(t => { if (tags.indexOf(t) === -1) tags.push(t); });
      }
    });
    CATEGORIES.slice(1).forEach(c => { if (lower.indexOf(c.toLowerCase()) !== -1 && cats.indexOf(c) === -1) cats.push(c); });
    TAG_VOCAB.forEach(t => { if (lower.indexOf(t) !== -1 && tags.indexOf(t) === -1) tags.push(t); });
    const keywords = q.split(/[\s,./]+/).filter(t => t.length >= 2 && STOP.indexOf(t) === -1).slice(0, 4).map(t => t.slice(0, 10));

    const scored = REFERENCES.map((r, idx) => {
      let s = 0;
      if (cats.indexOf(r.category) !== -1) s += 3;
      r.tags.forEach(t => { if (tags.indexOf(t) !== -1) s += 2; });
      keywords.forEach(k => { if ((r.title + r.desc).toLowerCase().indexOf(k.toLowerCase()) !== -1) s += 1; });
      return { r: r, s: s, idx: idx };
    }).filter(x => x.s > 0).sort((a, b) => b.s - a.s || a.idx - b.idx).slice(0, 8);

    const reasons = {}, items = [];
    scored.forEach(x => {
      items.push(x.r);
      const hit = x.r.tags.filter(t => tags.indexOf(t) !== -1);
      reasons[x.r.id] = hit.length ? hit.join('·') + ' 무드가 검색어와 맞아요' : (cats.indexOf(x.r.category) !== -1 ? x.r.category + ' 분야예요' : '검색어와 비슷한 키워드가 있어요');
    });

    const targetCats = cats.length ? cats : ['브랜딩', '포스터', '웹/UI', '일러스트'];
    const moods = tags.length ? tags : ['모던', '미니멀'];
    const kw = keywords[0] || '새로운';
    for (let i = 0; i < 4; i++) {
      const cat = targetCats[i % targetCats.length];
      const m1 = moods[i % moods.length], m2 = moods[(i + 1) % moods.length];
      const round = Math.floor(i / targetCats.length);
      const palKey = round ? m2 : m1;
      const mood = m1 === m2 ? [m1] : [m1, m2];
      const raw = {
        title: kw + ' ' + SUFFIX[cat] + (round ? ' ' + (round + 1) + '안' : ''), category: cat, tags: mood,
        desc: mood.join('·') + ' 무드로 ‘' + kw + '’ 주제를 풀어낸 ' + cat + ' 예시입니다. (데모 데이터)',
        colors: PALETTES[palKey] || DEFAULT_PALETTE, letter: kw.charAt(0), reason: '검색어를 바탕으로 만든 데모 제안이에요'
      };
      const it = registerItem(raw, 'ai-' + hash(q + '|' + raw.title + '|' + cat).toString(36), cat);
      if (it) items.push(it);
    }
    return {
      mode: 'demo',
      note: reason === 'error' ? 'ChatGPT 연결에 실패해 아래는 데모 결과예요. 원인: ' + detail : 'AI가 연결되지 않아 데모 해석으로 보여줘요.',
      noteKind: reason === 'error' ? 'error' : 'warn',
      categories: cats, tags: tags.slice(0, 5), keywords: keywords,
      summary: '‘' + clip(q, 30) + '’ 검색을 ' + (cats.length ? cats.join('·') : '모든 분야') + ', ' + (tags.length ? tags.join('·') : '무드 미지정') + ' 기준으로 해석했어요.',
      items: items, reasons: reasons
    };
  }

