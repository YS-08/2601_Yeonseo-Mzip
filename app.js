  const rect = (x, y, w, h, fill, ex) => `<rect x="${f1(x)}" y="${f1(y)}" width="${f1(w)}" height="${f1(h)}" fill="${fill}"${ex ? ' ' + ex : ''}/>`;
  const circ = (cx, cy, r, fill, ex) => `<circle cx="${f1(cx)}" cy="${f1(cy)}" r="${f1(r)}" fill="${fill}"${ex ? ' ' + ex : ''}/>`;
  function shade(hex, f) {
    const h = hex.slice(1);
    const m = c => Math.round(f >= 0 ? c + (255 - c) * f : c * (1 + f));
    return '#' + [0, 2, 4].map(i => m(parseInt(h.substr(i, 2), 16)).toString(16).padStart(2, '0')).join('').toUpperCase();
  }
  function rng(seed) {
    let a = seed >>> 0;
    return () => { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
  }

  const DRAW = {
    brand(w, h, p, rnd, n) {
      const cx = w / 2, cy = h * 0.40, r = w * 0.17, v = n % 3;
      let s = rect(0, 0, w, h, p[0]);
      if (v === 0) {
        s += circ(cx, cy, r, p[1]);
        s += `<path d="M${f1(cx - r)},${f1(cy)} A${f1(r)},${f1(r)} 0 0 0 ${f1(cx + r)},${f1(cy)} Z" fill="${p[2]}"/>`;
      } else if (v === 1) {
        s += rect(cx - r, cy - r, 2 * r, 2 * r, p[1], `rx="${f1(r * 0.25)}" transform="rotate(45 ${f1(cx)} ${f1(cy)})"`);
        s += circ(cx, cy, r * 0.35, p[0]);
      } else {
        s += `<circle cx="${f1(cx)}" cy="${f1(cy)}" r="${f1(r)}" fill="none" stroke="${p[1]}" stroke-width="${f1(r * 0.28)}"/>`;
        s += circ(cx + r * 0.55, cy - r * 0.55, r * 0.28, p[2]);
      }
      const by = h * 0.64;
      s += rect(w * 0.30, by, w * 0.40, h * 0.035, p[2], `rx="${f1(h * 0.0175)}"`);
      s += rect(w * 0.38, by + h * 0.06, w * 0.24, h * 0.018, p[2], `rx="${f1(h * 0.009)}" opacity=".35"`);
      const sw = h * 0.045;
      [p[1], p[2], shade(p[1], 0.5)].forEach((c, i) => { s += circ(w / 2 + (i - 1) * sw * 2.6, h * 0.88, sw, c); });
      return s;
    },
    poster(w, h, p, rnd, n) {
      const v = n % 3;
      let s = rect(0, 0, w, h, p[0]);
      if (v === 0) {
        s += circ(w * 0.5, h * 0.42, w * 0.30, p[1]);
        s += rect(w * 0.12, h * 0.60, w * 0.76, h * 0.08, p[2]);
      } else if (v === 1) {
        s += rect(w * 0.10, h * 0.08, w * 0.45, h * 0.55, p[1]);
        s += circ(w * 0.62, h * 0.52, w * 0.22, p[2]);
      } else {
        for (let i = 0; i < 5; i++) s += rect(w * 0.1, h * (0.10 + i * 0.10), w * (0.8 - i * 0.12), h * 0.07, i % 2 === 0 ? p[1] : p[2]);
      }
      s += rect(w * 0.10, h * 0.78, w * 0.55, h * 0.04, p[2]);
      s += rect(w * 0.10, h * 0.85, w * 0.32, h * 0.018, p[2], 'opacity=".5"');
      s += rect(w * 0.10, h * 0.89, w * 0.22, h * 0.018, p[2], 'opacity=".5"');
      return s;
    },
    ui(w, h, p, rnd, n) {
      const pad = w * 0.07, card = shade(p[0], 0.6);
      let s = rect(0, 0, w, h, p[0]);
      s += rect(pad, pad, w - 2 * pad, h - 2 * pad, card, 'rx="14"');
      s += rect(pad, pad, w - 2 * pad, h * 0.09, p[2], 'rx="14"');
      for (let i = 0; i < 3; i++) s += circ(pad + 22 + i * 18, pad + h * 0.045, 5, card, 'opacity=".7"');
      const top = pad + h * 0.13;
      if (n % 2 === 0) {
        const cw = (w - 2 * pad - 42) / 2;
        for (let i = 0; i < 2; i++) s += rect(pad + 14 + i * (cw + 14), top, cw, h * 0.26, p[1], `rx="10" opacity="${i === 0 ? 1 : 0.55}"`);
        for (let j = 0; j < 3; j++) s += rect(pad + 14, top + h * 0.31 + j * h * 0.09, (w - 2 * pad - 28) * (0.9 - j * 0.2), h * 0.04, p[2], `rx="6" opacity="${j ? 0.25 : 0.5}"`);
      } else {
        s += rect(pad + 14, top, w - 2 * pad - 28, h * 0.30, p[1], 'rx="10"');
        s += circ(w * 0.5, top + h * 0.15, h * 0.07, card, 'opacity=".85"');
        for (let j = 0; j < 3; j++) s += rect(pad + 14 + j * ((w - 2 * pad - 28) / 3), top + h * 0.35, (w - 2 * pad - 28) / 3 - 10, h * 0.16, p[2], `rx="8" opacity="${f1(0.18 + j * 0.12)}"`);
      }
      return s;
    },
    typo(w, h, p, rnd, n, letter) {
      const fs = Math.min(w, h) * 0.62;
      let s = rect(0, 0, w, h, p[0]);
      s += `<text x="${f1(w * 0.08)}" y="${f1(h * 0.68)}" font-family="Georgia, Apple SD Gothic Neo, Malgun Gothic, serif" font-size="${f1(fs)}" font-weight="700" fill="${p[1]}">${esc(letter || 'Aa')}</text>`;
      s += rect(w * 0.08, h * 0.78, w * 0.84, 2, p[2]);
      for (let i = 0; i < 3; i++) s += rect(w * 0.08, h * (0.83 + i * 0.045), w * (0.6 - i * 0.14), h * 0.016, p[2], 'opacity=".55"');
      s += circ(w * 0.84, h * 0.18, Math.min(w, h) * 0.06, p[2]);
      return s;
    },
    illust(w, h, p, rnd) {
      let s = rect(0, 0, w, h, p[0]) + circ(w * 0.7, h * 0.28, w * 0.13, p[1]);
      for (let i = 0; i < 3; i++) {
        const y = h * (0.55 + i * 0.13), c = [p[2], shade(p[2], -0.15), shade(p[2], -0.32)][i], amp = h * (0.06 + rnd() * 0.04);
        s += `<path d="M0,${f1(y)} C${f1(w * 0.25)},${f1(y - amp * 2)} ${f1(w * 0.5)},${f1(y + amp * 2)} ${f1(w * 0.75)},${f1(y - amp)} S${w},${f1(y)} ${w},${f1(y)} L${w},${h} L0,${h} Z" fill="${c}"/>`;
      }
      for (let i = 0; i < 4; i++) s += circ((0.08 + rnd() * 0.47) * w, (0.08 + rnd() * 0.34) * h, (0.03 + rnd() * 0.03) * w, p[1], 'opacity=".55"');
      return s;
    },
    package(w, h, p) {
      const bw = w * 0.46, bh = h * 0.40, x = w * 0.24, y = h * 0.34, d = w * 0.14;
      let s = rect(0, 0, w, h, p[0]);
      s += `<polygon points="${f1(x)},${f1(y)} ${f1(x + d)},${f1(y - d * 0.7)} ${f1(x + bw + d)},${f1(y - d * 0.7)} ${f1(x + bw)},${f1(y)}" fill="${shade(p[1], 0.35)}"/>`;
      s += `<polygon points="${f1(x + bw)},${f1(y)} ${f1(x + bw + d)},${f1(y - d * 0.7)} ${f1(x + bw + d)},${f1(y + bh - d * 0.7)} ${f1(x + bw)},${f1(y + bh)}" fill="${shade(p[1], -0.2)}"/>`;
      s += rect(x, y, bw, bh, p[1]);
      s += circ(x + bw / 2, y + bh * 0.45, bw * 0.17, p[0], 'opacity=".92"');
      s += rect(x + bw * 0.28, y + bh * 0.76, bw * 0.44, bh * 0.06, p[2], 'rx="3"');
      s += `<ellipse cx="${f1(x + bw / 2 + d / 2)}" cy="${f1(y + bh + h * 0.03)}" rx="${f1(bw * 0.62)}" ry="${f1(h * 0.018)}" fill="${p[2]}" opacity=".18"/>`;
      return s;
    }
  };

  function makeImage(item) {
    const w = 600, h = RATIO_H[item.ratio] || 600, seed = hash(item.id);
    const body = DRAW[item.kind](w, h, item.colors, rng(seed), seed % 9, item.letter);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${body}</svg>`;
    return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
  }

