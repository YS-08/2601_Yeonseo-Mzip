  function parseJson(text) {
    const t = String(text || '').trim().replace(/^```(?:json)?/i, '').replace(/```$/, '').trim();
    try { return JSON.parse(t); } catch (e) {
      const i = t.indexOf('{'), j = t.lastIndexOf('}');
      if (i !== -1 && j > i) return JSON.parse(t.slice(i, j + 1));
      throw e;
    }
  }

