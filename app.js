  function describeError(err) {
    const m = err && err.message ? ' (' + clip(err.message, 140) + ')' : '';
    if (err && err.name === 'AbortError') return '응답이 너무 오래 걸려 중단했어요. 더 빠른 모델(예: gpt-4o-mini)로 바꿔 보세요.';
    if (err && err.code === 'KEY_CHARS') return 'API 키에 올바르지 않은 문자가 들어 있어요. 키를 다시 복사해 붙여넣어 주세요.';
    if (err && err.empty) return 'AI가 쓸 수 있는 결과를 돌려주지 않았어요. 다시 시도해 주세요.';
    if (err && err.status === 401) return 'API 키가 올바르지 않거나 만료됐어요' + m + '.';
    if (err && err.status === 403) return 'API 접근이 거부됐어요. 프로젝트 권한이나 사용 지역을 확인해 주세요' + m + '.';
    if (err && err.status === 404) return '모델을 찾을 수 없어요. 설정에서 모델 이름을 확인해 주세요' + m + '.';
    if (err && err.status === 429) return '사용 한도 초과 또는 결제(크레딧) 문제예요' + m + '.';
    if (err && err.status) return '서버 오류 ' + err.status + m + '.';
    if (err instanceof SyntaxError) return 'AI 응답 형식이 올바르지 않았어요. 다시 시도해 주세요.';
    return state.backend.available
      ? '로컬 서버 요청이 실패했어요.'
      : '브라우저에서 OpenAI로 직접 연결하지 못했어요. 브라우저 보안(CORS)·네트워크·미리보기 화면 제한 때문일 수 있어요. 터미널에서 node server.js 로 실행한 뒤 http://localhost:3000 으로 열면 해결돼요.';
  }

  async function httpError(res) {
    let msg = '';
    try { const j = await res.json(); msg = (j && j.error && (j.error.message || j.error)) || ''; } catch (e) { /* 무시 */ }
    const err = new Error(typeof msg === 'string' ? msg : ''); err.status = res.status; return err;
  }

  // 서버 경유(server) 또는 브라우저 직접(direct)으로 Chat Completions 호출
  async function callChat(messages, mode, timeoutMs) {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), timeoutMs || AI_CONFIG.timeoutMs);
    try {
      let res;
      if (mode === 'server') {
        res = await fetch(API_BASE + '/api/chat', { method: 'POST', signal: ctrl.signal, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ messages: messages }) });
      } else {
        const key = cleanKey(state.ai.key);
        const send = jsonMode => fetch(AI_CONFIG.endpoint, {
          method: 'POST', signal: ctrl.signal,
          headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + key },
          body: JSON.stringify(Object.assign({ model: state.ai.model, messages: messages }, jsonMode ? { response_format: { type: 'json_object' } } : {}))
        });
        res = await send(true);
        if (res.status === 400) { const t = await res.clone().text(); if (/response_format|json_object|json mode/i.test(t)) res = await send(false); }
      }
      if (!res.ok) throw await httpError(res);
      const data = await res.json();
      const text = data && data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content;
      if (!text) { const e = new Error('empty-content'); e.empty = true; throw e; }
      return text;
    } finally { clearTimeout(timer); }
  }

  async function searchWithChatGPT(q, mode) {
    const text = await callChat([{ role: 'system', content: buildSystemPrompt() }, { role: 'user', content: q }], mode);
    const result = normalizeAi(parseJson(text), q, 'chatgpt', '');
    if (!result.items.length) { const e = new Error('no-items'); e.empty = true; throw e; }
    result.via = mode; result.model = modelInUse(mode);
    return result;
  }

